"use client";

import { useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { ShieldCheck } from "lucide-react";
import { AuthLayout } from "@/components/shared/auth-layout";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import type { AdminOperator } from "@/lib/admin-operator";
import { startEnrollment, verifyTotp } from "./actions";

type VerifiedFactor = { id: string; operator: AdminOperator };

export function MfaPanel({
  next,
  required,
  verifiedFactors,
  unenrolledOperators,
  unrecognizedFactor,
  onSignOut,
}: {
  next: string;
  required: boolean;
  verifiedFactors: VerifiedFactor[];
  unenrolledOperators: readonly AdminOperator[];
  unrecognizedFactor: boolean;
  onSignOut: () => Promise<void>;
}) {
  const router = useRouter();
  const [factorId, setFactorId] = useState<string | null>(null);
  const [enrolling, setEnrolling] = useState<{ operator: AdminOperator; qrCode: string; secret: string } | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [isPending, startTransition] = useTransition();

  function beginEnroll(operator: AdminOperator) {
    setError(null);
    startTransition(async () => {
      const result = await startEnrollment(operator);
      if ("error" in result) {
        setError(result.error);
        return;
      }
      setEnrolling({ operator, qrCode: result.qrCode, secret: result.secret });
      setFactorId(result.factorId);
      setCode("");
    });
  }

  function submit(event: React.FormEvent) {
    event.preventDefault();
    if (!factorId) return;
    setError(null);
    startTransition(async () => {
      const result = await verifyTotp(factorId, code, next);
      if ("error" in result) {
        setError(result.error);
        setCode("");
        return;
      }
      router.push(result.next);
      router.refresh();
    });
  }

  const showCodeStep = factorId !== null;

  return (
    <AuthLayout>
      <div className="space-y-5 rounded-xl border border-border bg-surface p-7 shadow-raised sm:p-8">
        <div className="space-y-1.5">
          <h1 className="flex items-center gap-2 text-lg font-semibold tracking-tight">
            <ShieldCheck className="size-5" /> Admin verification
          </h1>
          <p className="text-sm text-muted-foreground">
            {required
              ? "The platform admin console needs a code from your authenticator app."
              : "Add your authenticator app now so the admin console can require it. Nothing is enforced until the owner switches it on."}
          </p>
          {unrecognizedFactor ? (
            <p className="text-sm text-destructive">
              This account has an authenticator that is not on the approved list. Ask the platform owner to review it.
            </p>
          ) : null}
        </div>

        {enrolling ? (
          <div className="space-y-3">
            <p className="text-sm">Scan this with your authenticator app, then enter the 6-digit code ({enrolling.operator}).</p>
            {/* data: URI generated by Supabase Auth; CSP img-src already allows data: */}
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={enrolling.qrCode} alt="Authenticator QR code" className="mx-auto size-44 rounded-md bg-white p-2" />
            <p className="break-all text-center text-xs text-muted-foreground">Or enter this key: {enrolling.secret}</p>
          </div>
        ) : null}

        {showCodeStep ? (
          <form onSubmit={submit} className="space-y-3">
            <Input
              autoFocus
              inputMode="numeric"
              pattern="\d{6}"
              maxLength={6}
              placeholder="000000"
              value={code}
              onChange={(e) => setCode(e.target.value.replace(/\D/g, "").slice(0, 6))}
              className="text-center text-lg tracking-[0.4em]"
            />
            <Button type="submit" disabled={isPending || code.length !== 6} className="h-11 w-full">
              {isPending ? "Verifying…" : "Verify"}
            </Button>
          </form>
        ) : (
          <div className="space-y-4">
            {verifiedFactors.length > 0 ? (
              <div className="space-y-2">
                <p className="text-sm font-medium">Sign in as</p>
                {verifiedFactors.map((f) => (
                  <Button
                    key={f.id}
                    type="button"
                    variant="outline"
                    disabled={isPending}
                    onClick={() => {
                      setError(null);
                      setEnrolling(null);
                      setFactorId(f.id);
                      setCode("");
                    }}
                    className="h-11 w-full justify-start"
                  >
                    {f.operator}
                  </Button>
                ))}
              </div>
            ) : null}

            {unenrolledOperators.length > 0 ? (
              <div className="space-y-2">
                <p className="text-sm font-medium">Set up an authenticator for</p>
                {unenrolledOperators.map((name) => (
                  <Button
                    key={name}
                    type="button"
                    variant="ghost"
                    disabled={isPending}
                    onClick={() => beginEnroll(name)}
                    className="h-10 w-full justify-start"
                  >
                    {name}
                  </Button>
                ))}
              </div>
            ) : null}
          </div>
        )}

        {error ? <p className="text-sm text-destructive">{error}</p> : null}

        <button
          type="button"
          onClick={() => void onSignOut()}
          className="w-full text-center text-xs text-muted-foreground hover:text-foreground"
        >
          Sign out
        </button>
      </div>
    </AuthLayout>
  );
}
