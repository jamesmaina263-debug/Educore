"use server";

import { revalidatePath } from "next/cache";
import { createClient } from "@/lib/supabase/server";
import { extractEdgeFunctionError } from "@/lib/edge-function-error";

type ActionResult = { error: string } | { success: true };

export async function generateNemisBatch(
  batchType: "new_admissions" | "full_roster",
  studentIds: string[] | null,
  notes?: string,
): Promise<{ error: string } | { success: true; batchId: string }> {
  const supabase = await createClient();

  const { data, error } = await supabase.rpc("generate_nemis_sync_batch", {
    p_batch_type: batchType,
    p_student_ids: studentIds,
    p_notes: notes?.trim() || null,
  });
  if (error) return { error: error.message };

  revalidatePath("/integrations/nemis");
  return { success: true as const, batchId: data as string };
}

